import os
import sys
import tkinter as tk
from tkinter import ttk, messagebox


def get_env_path() -> str:
    """
    Returns the path where .env lives or should be saved.
    Prefers next to exe/script if writable, falls back to %APPDATA%/AlfredX/.env.
    """
    if getattr(sys, "frozen", False):
        exe_dir = os.path.dirname(sys.executable)
        next_to_exe = os.path.join(exe_dir, ".env")
        if os.path.exists(next_to_exe):
            return next_to_exe
        try:
            test_file = os.path.join(exe_dir, ".perm_test")
            with open(test_file, "w") as f:
                f.write("ok")
            os.remove(test_file)
            return next_to_exe
        except Exception:
            app_data = os.path.join(os.environ.get("APPDATA", os.path.expanduser("~")), "AlfredX")
            os.makedirs(app_data, exist_ok=True)
            return os.path.join(app_data, ".env")
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), ".env")


PLACEHOLDERS = {
    "GROQ_API_KEY": "gsk_your_groq_api_key",
    "GMAIL_ADDRESS": "yourname@gmail.com",
    "GMAIL_APP_PASSWORD": "xxxx xxxx xxxx xxxx",
    "WEATHER_API_KEY": "your_openweathermap_key",
    "NEWS_API_KEY": "your_newsapi_key",
    "SPOTIFY_CLIENT_ID": "your_spotify_client_id",
    "SPOTIFY_CLIENT_SECRET": "your_spotify_client_secret",
    "SPOTIFY_REDIRECT_URI": "https://localhost:8888/callback",
}


def env_exists() -> bool:
    """
    Returns True only if .env exists AND at least one real key is configured
    or setup was already completed/skipped.
    """
    env_file = get_env_path()
    if not os.path.exists(env_file):
        return False
    values = _load_env_values()
    if values.get("SETUP_COMPLETED") == "true":
        return True
    for key in ("GROQ_API_KEY", "GMAIL_ADDRESS"):
        val = values.get(key, "").strip()
        placeholder = PLACEHOLDERS.get(key, "")
        if val and val != placeholder and not val.startswith("your"):
            return True
    return False


def _load_env_values() -> dict:
    """Read existing .env file into a dict."""
    values = {}
    env_file = get_env_path()
    if not os.path.exists(env_file):
        return values
    with open(env_file, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                key, _, val = line.partition("=")
                values[key.strip()] = val.strip()
    return values


def save_env(data: dict):
    """Write key=value pairs to .env file."""
    env_file = get_env_path()
    lines = [
        "# AlfredX Configuration — Auto-generated by Setup Wizard",
        "# Edit here or re-open Settings from the AlfredX menu",
        "",
        "SETUP_COMPLETED=true",
    ]
    for key, value in data.items():
        if key != "SETUP_COMPLETED":
            lines.append(f"{key}={value.strip()}")
    with open(env_file, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    # Reload into environment immediately so app picks up new values
    os.environ["SETUP_COMPLETED"] = "true"
    for key, value in data.items():
        os.environ[key] = value.strip()


def open_settings():
    """
    Call this from your main GUI's Settings button.
    Opens the wizard in update mode (pre-filled with existing values).
    """
    run_wizard(update_mode=True)


def run_wizard(update_mode: bool = False) -> bool:
    """
    Launch the setup wizard GUI.
    update_mode=True  → pre-fills fields with existing .env values (for Settings)
    update_mode=False → first-time setup
    Returns True if setup was completed/saved.
    """
    existing = _load_env_values() if update_mode else {}
    result = {"completed": False}

    # ── Root window ──────────────────────────────────────────
    root = tk.Tk()
    title = "AlfredX — Update Settings" if update_mode else "AlfredX — First Time Setup"
    root.title(title)
    root.geometry("600x850")
    root.resizable(False, False)
    root.configure(bg="#1a1a2e")

    root.update_idletasks()
    x = (root.winfo_screenwidth() - 600) // 2
    y = (root.winfo_screenheight() - 850) // 2
    root.geometry(f"600x850+{x}+{y}")

    BG = "#1a1a2e"
    CARD = "#16213e"
    ACCENT = "#e94560"
    TEXT = "#eaeaea"
    MUTED = "#888"
    ENTRY_BG = "#0f3460"

    header = tk.Frame(root, bg=ACCENT, height=6)
    header.pack(fill="x")

    heading = "⚙️  Update Settings" if update_mode else "🤖  AlfredX"
    subheading = "Update your API Keys & Credentials" if update_mode else "First Time Setup — Enter Your API Keys"
    tk.Label(root, text=heading, font=("Segoe UI", 22, "bold"),
             bg=BG, fg=TEXT).pack(pady=(20, 2))
    tk.Label(root, text=subheading,
             font=("Segoe UI", 11), bg=BG, fg=MUTED).pack(pady=(0, 15))

    canvas = tk.Canvas(root, bg=BG, highlightthickness=0)
    scrollbar = ttk.Scrollbar(root, orient="vertical", command=canvas.yview)
    scroll_frame = tk.Frame(canvas, bg=BG)

    scroll_frame.bind("<Configure>",
                      lambda e: canvas.configure(scrollregion=canvas.bbox("all")))
    canvas.create_window((0, 0), window=scroll_frame, anchor="nw")
    canvas.configure(yscrollcommand=scrollbar.set)

    btn_frame = tk.Frame(root, bg=BG)
    btn_frame.pack(side="bottom", pady=12)

    canvas.pack(side="left", fill="both", expand=True, padx=(20, 0))
    scrollbar.pack(side="right", fill="y")

    def _on_mousewheel(event):
        canvas.yview_scroll(int(-1 * (event.delta / 120)), "units")
    canvas.bind_all("<MouseWheel>", _on_mousewheel)

    entries = {}

    def add_section(title, fields, subtitle=None):
        card = tk.Frame(scroll_frame, bg=CARD, bd=0, relief="flat")
        card.pack(fill="x", padx=10, pady=8, ipady=8)
        tk.Label(card, text=title, font=("Segoe UI", 11, "bold"),
                 bg=CARD, fg=ACCENT).pack(anchor="w", padx=15, pady=(10, 2))
        if subtitle:
            tk.Label(card, text=subtitle, font=("Segoe UI", 8),
                     bg=CARD, fg=MUTED, wraplength=540).pack(anchor="w", padx=15, pady=(0, 4))
        ttk.Separator(card, orient="horizontal").pack(fill="x", padx=15, pady=(0, 8))

        for label, key, placeholder, is_pass in fields:
            row = tk.Frame(card, bg=CARD)
            row.pack(fill="x", padx=15, pady=3)
            tk.Label(row, text=label, font=("Segoe UI", 9),
                     bg=CARD, fg=TEXT, width=22, anchor="w").pack(side="left")

            var = tk.StringVar()
            e = tk.Entry(row, textvariable=var, font=("Segoe UI", 9),
                         bg=ENTRY_BG, fg=TEXT, insertbackground=TEXT,
                         relief="flat", bd=4,
                         show="●" if is_pass else "")
            e.pack(side="left", fill="x", expand=True)

            # Pre-fill with existing value if update_mode, else show placeholder
            saved_val = existing.get(key, "")
            if saved_val and saved_val not in (placeholder, "") and not saved_val.startswith("your"):
                e.insert(0, saved_val)
                e.config(fg=TEXT)
            else:
                e.insert(0, placeholder)
                e.config(fg=MUTED)

            def on_focus_in(event, entry=e, ph=placeholder):
                if entry.get() == ph:
                    entry.delete(0, tk.END)
                    entry.config(fg=TEXT)

            def on_focus_out(event, entry=e, ph=placeholder):
                if not entry.get():
                    entry.insert(0, ph)
                    entry.config(fg=MUTED)

            e.bind("<FocusIn>", on_focus_in)
            e.bind("<FocusOut>", on_focus_out)
            entries[key] = (var, placeholder)

    add_section("🧠  Groq AI (Online Mode — free)",
                [("Groq API Key", "GROQ_API_KEY", PLACEHOLDERS["GROQ_API_KEY"], True)],
                subtitle="Required for Online Mode. Get a free key at console.groq.com/keys")

    add_section("📧  Gmail (for sending/checking emails)", [
        ("Gmail Address", "GMAIL_ADDRESS", PLACEHOLDERS["GMAIL_ADDRESS"], False),
        ("Gmail App Password", "GMAIL_APP_PASSWORD", PLACEHOLDERS["GMAIL_APP_PASSWORD"], True),
    ])

    add_section("🌤  Weather (openweathermap.org — free)", [
        ("Weather API Key", "WEATHER_API_KEY", PLACEHOLDERS["WEATHER_API_KEY"], True),
    ])

    add_section("📰  News (newsapi.org — free)", [
        ("News API Key", "NEWS_API_KEY", PLACEHOLDERS["NEWS_API_KEY"], True),
    ])

    add_section("🎵  Spotify (developer.spotify.com — optional)", [
        ("Client ID", "SPOTIFY_CLIENT_ID", PLACEHOLDERS["SPOTIFY_CLIENT_ID"], False),
        ("Client Secret", "SPOTIFY_CLIENT_SECRET", PLACEHOLDERS["SPOTIFY_CLIENT_SECRET"], True),
        ("Redirect URI", "SPOTIFY_REDIRECT_URI", PLACEHOLDERS["SPOTIFY_REDIRECT_URI"], False),
    ])

    ollama_note = tk.Frame(scroll_frame, bg="#0d2137")
    ollama_note.pack(fill="x", padx=10, pady=(0, 4), ipady=6)
    tk.Label(ollama_note,
             text="🖥  Offline Mode (Ollama) — No API key needed! Just make sure Ollama is installed and running.",
             font=("Segoe UI", 8), bg="#0d2137", fg=MUTED, wraplength=540).pack(padx=12)

    env_path_note = tk.Frame(scroll_frame, bg="#0d2137")
    env_path_note.pack(fill="x", padx=10, pady=(4, 12), ipady=6)
    tk.Label(env_path_note,
             text=f"ℹ  Keys saved to: {get_env_path()}",
             font=("Segoe UI", 8), bg="#0d2137", fg=MUTED, wraplength=540).pack(padx=12)

    def on_save():
        data = {}
        for key, (var, placeholder) in entries.items():
            value = var.get().strip()
            if value == placeholder or value == "":
                # Keep existing value if in update mode, else empty
                value = existing.get(key, "")
            data[key] = value

        # In first-time mode, require at least GROQ or GMAIL
        if not update_mode:
            groq_val = data.get("GROQ_API_KEY", "")
            gmail_val = data.get("GMAIL_ADDRESS", "")
            if (not groq_val or groq_val.startswith("your")) and \
               (not gmail_val or gmail_val.startswith("your") or "@" not in gmail_val):
                messagebox.showwarning(
                    "Almost there!",
                    "Please fill in at least your Groq API Key OR Gmail address to continue."
                )
                return

        save_env(data)
        result["completed"] = True
        msg = "Settings updated! Changes take effect immediately." if update_mode else \
              "AlfredX is ready to use!\nClick OK to launch."
        messagebox.showinfo("✅ Saved!", msg)
        root.destroy()

    def on_skip():
        if update_mode:
            root.destroy()
            return
        if messagebox.askyesno("Skip Setup?",
                               "Skip setup? AlfredX may not work without API keys.\n\n"
                               "You can update keys later from the Settings menu."):
            save_env({k: "" for k in PLACEHOLDERS})
            result["completed"] = True
            root.destroy()

    if not update_mode:
        tk.Button(btn_frame, text="Skip for now", font=("Segoe UI", 9),
                  bg=CARD, fg=MUTED, relief="flat", padx=16, pady=6,
                  cursor="hand2", command=on_skip).pack(side="left", padx=8)
    else:
        tk.Button(btn_frame, text="Cancel", font=("Segoe UI", 9),
                  bg=CARD, fg=MUTED, relief="flat", padx=16, pady=6,
                  cursor="hand2", command=on_skip).pack(side="left", padx=8)

    save_label = "  Update Settings  " if update_mode else "  Save & Launch AlfredX  "
    tk.Button(btn_frame, text=save_label,
              font=("Segoe UI", 10, "bold"),
              bg=ACCENT, fg="white", relief="flat", padx=20, pady=8,
              cursor="hand2", command=on_save).pack(side="left", padx=8)

    root.mainloop()
    return result["completed"]


if __name__ == "__main__":
    run_wizard()
